describe('the css prop', () => {
  it('compiles in .tsx modules without importing Compiled, into an extracted stylesheet', async () => {
    const { transform, stylesheet } = await serve({
      'src/Card.tsx': `import type { ReactNode } from 'react';
interface Props { children: ReactNode }
export const Card = ({ children }: Props) => (
  <section css={{ color: 'red' }}>{children}</section>
);`,
    });
    const code = await transform('src/Card.tsx');
    assert.match(code, /className: ax\(\["_syaz5scu"\]\)/);
    assert.doesNotMatch(code, /\bcss:/);
    assert.equal(await stylesheet(code), '._syaz5scu{color:red}');
    // React's dev runtime gets the line of <section>.
    assert.match(code, /lineNumber: 4,/);
  });

  it('reads values from imported modules, through string aliases and from the root', async () => {
    const { transform, stylesheet } = await serve(
      {
        'src/colors/a.ts': `export const red = 'red';`,
        'src/colors/b.ts': `export const blue = 'blue';`,
        'src/Page.jsx': `
          import { red } from '@colors/a';
          import { blue } from '#/colors/b';
          export const Page = () => <p css={{ color: red, ':hover': { color: blue } }} />;
        `,
      },
      root => ({
        resolve: { alias: { '@colors': `${root}/src/colors`, '#': '/src' } },
      }),
    );
    const css = await stylesheet(await transform('src/Page.jsx'));
    assert.match(css, /\{color:red\}/);
    assert.match(css, /:hover\{color:blue\}/);
  });

  it('uses the runtime instead when extraction is off for the command', async () => {
    const { transform } = await serve(
      { 'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;` },
      { extract: { build: true, serve: false } },
    );
    const code = await transform('src/Card.jsx');
    assert.match(code, /\bCS\b/);
    assert.doesNotMatch(code, /virtual:vite-plugin-compiled-react/);
  });
});

describe('which modules are compiled', () => {
  it("parses TypeScript in .ts modules, where `<string>value` isn't JSX", async () => {
    const { transform } = await serve({
      'src/styles.ts': `
        import { css } from '@compiled/react';
        const value: unknown = 'red';
        export const color = <string>value;
        export const styles = css({ color: 'blue' });
      `,
    });
    // Compiled replaces css() calls with null: their styles are compiled where they're used.
    assert.match(await transform('src/styles.ts'), /export const styles = null;/);
  });

  it('compiles styled components in .ts modules', async () => {
    const { transform, stylesheet } = await serve({
      'src/Box.ts': `
        import { styled } from '@compiled/react';
        export const Box = styled.div({ color: 'red' });
      `,
    });
    const code = await transform('src/Box.ts');
    assert.match(code, /className: ax\(\["_syaz5scu", __cmplp\.className\]\)/);
    assert.equal(await stylesheet(code), '._syaz5scu{color:red}');
  });

  it("leaves alone modules that can't use Compiled, and dependencies", async () => {
    const { transform } = await serve({
      'src/plain.ts': `import './plain.css'; export const n: number = 1;`,
      'src/plain.css': ``,
      'node_modules/dep/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
    });
    assert.doesNotMatch(await transform('src/plain.ts'), /generated by @compiled/);
    assert.match(await transform('node_modules/dep/Card.jsx'), /\bcss:/);
  });
});

describe('the stylesheet', () => {
  it("holds every module's rules once, in Compiled's order, and is fetched anew by a module adding rules", async () => {
    const { transform, stylesheet } = await serve({
      'src/Banner.jsx': `export const Banner = () => <p css={{ color: 'green', '@media (min-width: 600px)': { color: 'blue' } }} />;`,
      'src/Card.jsx': `export const Card = () => <p css={{ color: 'red', '@media (min-width: 600px)': { color: 'blue' } }} />;`,
    });
    const banner = await transform('src/Banner.jsx');
    assert.equal(
      await stylesheet(banner),
      '._syazbf54{color:green}@media (min-width:600px){._10s713q2{color:blue}}',
    );
    const card = await transform('src/Card.jsx');
    assert.notEqual(stylesheetImport(card), stylesheetImport(banner));
    // Rules of the same kind are in the same order whichever module compiles first.
    assert.equal(
      await stylesheet(card),
      '._syaz5scu{color:red}._syazbf54{color:green}@media (min-width:600px){._10s713q2{color:blue}}',
    );
  });

  it('is linked by the HTML in a build, with the rules of lazily loaded modules', async () => {
    const root = await fixture({
      'index.html': `<script type="module" src="/src/main.jsx"></script>`,
      'src/main.jsx': `
        export const Card = () => <p css={{ color: 'red', '@media (min-width: 600px)': { color: 'blue' } }} />;
        import('./About.jsx');
      `,
      'src/About.jsx': `export const About = () => <p css={{ color: 'red', ':hover': { color: 'green' } }} />;`,
    });
    const { output } = await build({
      root,
      configFile: false,
      logLevel: 'silent',
      plugins: [compiled()],
      build: { write: false, rollupOptions: { external: [/^react/, /^@compiled\/react/] } },
    });
    const html = output.find(({ fileName }) => fileName === 'index.html').source;
    const links = [...html.matchAll(/<link rel="stylesheet"[^>]* href="\/([^"]+)"/g)];
    assert.equal(links.length, 1);
    const sheet = output.find(({ fileName }) => fileName === links[0][1]).source;
    assert.equal(
      sheet,
      '._syaz5scu{color:red}._30l3bf54:hover{color:green}@media (min-width:600px){._10s713q2{color:blue}}',
    );
  });

  it("goes into a library's own stylesheet, the file Vite names after the library", async () => {
    const buildLibrary = async (files, lib, buildOptions) => {
      const [{ output }] = await build({
        root: await fixture(files),
        configFile: false,
        logLevel: 'silent',
        plugins: [compiled()],
        build: {
          ...buildOptions,
          write: false,
          lib: { entry: 'src/index.jsx', formats: ['es'], ...lib },
          rollupOptions: { external: [/^react/, /^@compiled\/react/] },
        },
      });
      return output.flatMap(({ fileName, source }) =>
        fileName.endsWith('.css') ? [[fileName, source.replace(/\/\*\$vite\$:\d+\*\/|\n/g, '')]] : [],
      );
    };
    const card = `export const Card = () => <p css={{ color: 'red' }} />;`;
    assert.deepEqual(
      await buildLibrary(
        { 'src/index.jsx': `import './own.css';\n${card}`, 'src/own.css': `.own { color: blue }` },
        { fileName: 'my-lib' },
      ),
      [['my-lib.css', '.own{color:#00f}._syaz5scu{color:red}']],
    );
    assert.deepEqual(
      await buildLibrary(
        { 'package.json': `{ "name": "@acme/ui" }`, 'src/index.jsx': card },
        {},
      ),
      [['ui.css', '._syaz5scu{color:red}']],
    );
    assert.deepEqual(
      await buildLibrary({ 'src/index.jsx': card }, { fileName: 'ui', cssFileName: 'styles' }),
      [['styles.css', '._syaz5scu{color:red}']],
    );
    // With its CSS split, each entry's stylesheet has the rules of the entry's modules, sorted.
    assert.deepEqual(
      await buildLibrary(
        {
          'src/index.jsx': `import './own.css';\n${card}`,
          'src/own.css': `.own { color: blue }`,
          'src/Wide.jsx': `export const Wide = () => <p css={{ color: 'green', '@media (min-width: 600px)': { color: 'blue' } }} />;`,
          'src/banner.jsx': `export { Wide } from './Wide';\nexport const Banner = () => <p css={{ color: 'red' }} />;`,
        },
        { entry: { index: 'src/index.jsx', banner: 'src/banner.jsx' } },
        { cssCodeSplit: true },
      ),
      [
        ['index.css', '.own{color:#00f}._syaz5scu{color:red}'],
        ['banner.css', '._syaz5scu{color:red}._syazbf54{color:green}@media (min-width:600px){._10s713q2{color:blue}}'],
      ],
    );
  });

  it("goes into a library's stylesheet when Vite's app builder builds it", async () => {
    // The app builder loads the config file again for each environment it builds.
    const builder = await createBuilder({
      root: await fixture({
        'vite.config.js': `
          import { compiled } from '../lib/index.js';
          export default {
            logLevel: 'silent',
            plugins: [compiled()],
            build: {
              write: false,
              lib: { entry: 'src/index.jsx', formats: ['es'], fileName: 'my-lib' },
              rollupOptions: { external: [/^react/, /^@compiled\\/react/] },
            },
          };
        `,
        'src/index.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
      }),
    });
    const [{ output }] = await builder.build(builder.environments.client);
    assert.equal(
      output.find(({ fileName }) => fileName === 'my-lib.css')?.source,
      '._syaz5scu{color:red}',
    );
  });

  it('keeps the newest rules in dev when a page runs an older version after a newer one', async () => {
    const { transform, script } = await serve({
      'src/Banner.jsx': `export const Banner = () => <p css={{ color: 'green' }} />;`,
      'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
    });
    const older = await script(await transform('src/Banner.jsx'));
    const newer = await script(await transform('src/Card.jsx'));
    const page = browserPage();
    await page.run(newer);
    await page.run(older);
    assert.equal(
      page.document.querySelector('style').textContent,
      '._syaz5scu{color:red}._syazbf54{color:green}',
    );
  });

  it('goes after every link to it in dev, since Vite updates one of them', async () => {
    const { transform, script } = await serve({
      'src/Banner.jsx': `export const Banner = () => <p css={{ color: 'green' }} />;`,
      'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
    });
    const older = await script(await transform('src/Banner.jsx'));
    const newer = await script(await transform('src/Card.jsx'));
    const href = '/@id/__x00__virtual:vite-plugin-compiled-react.css';
    const page = browserPage(`<link rel="stylesheet" href="${href}?direct">`);
    await page.run(older);
    // A React Server Components payload links it again.
    page.document.head.insertAdjacentHTML('beforeend', `<link rel="stylesheet" href="${href}">`);
    await page.run(newer);
    assert.deepEqual(
      [...page.document.head.children].map(sheet => sheet.getAttribute('href') ?? sheet.textContent),
      [`${href}?direct`, href, '._syaz5scu{color:red}._syazbf54{color:green}'],
    );
  });

  it('is sent to pages that loaded it in dev when rules are added, also by a server environment', async () => {
    const { server, transform } = await serve({
      'src/Banner.jsx': `export const Banner = () => <p css={{ color: 'green' }} />;`,
      'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
    });
    const { client, ssr } = server.environments;
    await client.transformRequest(stylesheetImport(await transform('src/Banner.jsx')));
    const sent = [];
    client.hot.send = payload => sent.push(payload);
    await ssr.transformRequest('/src/Card.jsx');
    assert.deepEqual(
      sent.flatMap(({ updates }) => updates.map(({ type, path }) => [type, path])),
      [['js-update', '/@id/__x00__virtual:vite-plugin-compiled-react.js']],
    );
  });
});

describe('React Server environments', () => {
  it('extract, and import the Compiled runtime', async () => {
    const { server } = await serve(
      { 'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;` },
      {
        extract: false,
        environments: {
          rsc: {
            consumer: 'server',
            // Bundles @compiled/react, and React, whose modules only see the condition then.
            resolve: { conditions: ['react-server'], noExternal: true },
            optimizeDeps: { include: ['react', 'react/jsx-dev-runtime'] },
            dev: { createEnvironment: createRunnableDevEnvironment },
          },
        },
      },
    );
    const { Card } = await server.environments.rsc.runner.import('/src/Card.jsx');
    assert.equal(Card().props.className, '_syaz5scu');
  });
});

describe('dev', () => {
  it("pre-bundles Compiled's runtime, which compiled modules import, for the browser only", async () => {
    const { server } = await serve({});
    const { client, ssr } = server.environments;
    assert.ok(client.config.optimizeDeps.include.includes('@compiled/react/runtime'));
    assert.ok(!ssr.config.optimizeDeps.include?.includes('@compiled/react/runtime'));
  });

  it('re-compiles a module when a module it read values from changes', async () => {
    const fixture = await serve({
      'src/palette.ts': `export const red = 'red';`,
      'src/colors.ts': `import { red } from './palette'; export const color = red;`,
      'src/Card.jsx': `
        import { color } from './colors';
        export const Card = () => <p css={{ color }} />;
      `,
    });
    assert.match(await fixture.stylesheet(await fixture.transform('src/Card.jsx')), /color:red/);
    await edit(fixture, 'src/palette.ts', `export const red = 'blue';`);
    await eventually(
      async () => fixture.stylesheet(await fixture.transform('src/Card.jsx')),
      /color:blue/,
    );
  });

  it('re-compiles a module whose styles read an object through a re-export', async () => {
    const fixture = await serve({
      'src/palette.ts': `export const styles = { card: { color: 'red' } };`,
      'src/styles.ts': `export { styles } from './palette';`,
      'src/Card.jsx': `
        import { styles } from './styles';
        export const Card = () => <p css={styles.card} />;
      `,
    });
    assert.match(await fixture.stylesheet(await fixture.transform('src/Card.jsx')), /color:red/);
    await edit(fixture, 'src/palette.ts', `export const styles = { card: { color: 'blue' } };`);
    await eventually(
      async () => fixture.stylesheet(await fixture.transform('src/Card.jsx')),
      /color:blue/,
    );
  });

  it('re-compiles a module when a file in the middle of a chain of imports changes', async () => {
    const fixture = await serve({
      'src/palette.ts': `export const palette = { red: 'red', blue: 'blue' };`,
      'src/theme.ts': `import { palette } from './palette'; export const theme = { accent: palette.red };`,
      'src/styles.ts': `import { theme } from './theme'; export const styles = { card: { color: theme.accent } };`,
      'src/Card.jsx': `
        import { styles } from './styles';
        export const Card = () => <p css={styles.card} />;
      `,
    });
    assert.match(await fixture.stylesheet(await fixture.transform('src/Card.jsx')), /color:red/);
    await edit(
      fixture,
      'src/theme.ts',
      `import { palette } from './palette'; export const theme = { accent: palette.blue };`,
    );
    await eventually(
      async () => fixture.stylesheet(await fixture.transform('src/Card.jsx')),
      /color:blue/,
    );
  });

  it("doesn't update a module for a change that only reaches it through a component it imports", async () => {
    const fixture = await serve({
      'src/clock.ts': `export const now = 1;`,
      'src/Header.jsx': `import { now } from './clock'; export const Header = () => <h1>{now}</h1>; import.meta.hot.accept();`,
      'src/Card.jsx': `import { Header } from './Header'; export const Card = () => <p css={{ color: 'red' }}><Header /></p>; import.meta.hot.accept();`,
    });
    for (const file of ['src/Card.jsx', 'src/Header.jsx', 'src/clock.ts']) await fixture.transform(file);
    const sent = [];
    fixture.server.environments.client.hot.send = payload => sent.push(payload);
    await edit(fixture, 'src/clock.ts', `export const now = 2;`);
    await eventually(async () => JSON.stringify(sent), /Header\.jsx/);
    assert.doesNotMatch(JSON.stringify(sent), /Card\.jsx/);
  });

  it('updates a .tsx module whose import TypeScript removed once Compiled inlined its value', async () => {
    const fixture = await serve({
      'src/colors.ts': `export const primary = 'red';`,
      'src/tokens.ts': `export { primary } from './colors';`,
      'src/App.tsx': `
        import { primary } from './tokens';
        export const App = () => <p css={{ color: primary }} />;
        import.meta.hot.accept();
      `,
    });
    assert.doesNotMatch(await fixture.transform('src/App.tsx'), /tokens/);
    const sent = [];
    fixture.server.environments.client.hot.send = payload => sent.push(payload);
    await edit(fixture, 'src/colors.ts', `export const primary = 'blue';`);
    await eventually(async () => JSON.stringify(sent), /"path":"\/src\/App\.tsx"/);
    assert.match(await fixture.stylesheet(await fixture.transform('src/App.tsx')), /color:blue/);
  });
});

async function edit({ root, server }, file, content) {
  await writeFile(join(root, file), content);
  server.watcher.emit('change', join(root, file));
}

async function eventually(read, pattern) {
  let value;
  for (let i = 0; i < 50 && !pattern.test(value); i++) {
    await new Promise(resolve => setTimeout(resolve, 20));
    value = await read();
  }
  assert.match(value, pattern);
}

async function fixture(files) {
  const root = await mkdtemp(join(packageDir, '.fixture-'));
  for (const [file, content] of Object.entries(files)) {
    await mkdir(dirname(join(root, file)), { recursive: true });
    await writeFile(join(root, file), content);
  }
  return root;
}

// A page that runs modules served to the browser, with Vite's client stubbed.
let pages = 0;
function browserPage(head = '') {
  const page = ++pages;
  const { document } = new Window({
    url: 'http://localhost/',
    settings: { disableCSSFileLoading: true },
  });
  document.head.innerHTML = head;
  const hotData = {};
  const viteClient = `data:text/javascript,
    export const createHotContext = () => ({ data: hotData, accept() {} });
    export const updateStyle = (id, css) => {
      const style = [...document.querySelectorAll('style')].find(style => style.dataset.viteDevId === id) ??
        document.head.appendChild(document.createElement('style'));
      style.dataset.viteDevId = id;
      style.textContent = css;
    };`;
  return {
    document,
    async run(code) {
      Object.assign(globalThis, { document, hotData });
      // Each page runs the module anew: import() caches by URL.
      code = `${code.replace(/(["'])\/@vite\/client\1/g, JSON.stringify(viteClient))}\n// page ${page}`;
      await import(`data:text/javascript,${encodeURIComponent(code)}`);
    },
  };
}

// The id of the stylesheet a module imports, with its query.
function stylesheetImport(code) {
  const url = code.match(/import "\/@id\/__x00__(virtual:vite-plugin-compiled-react\.js[^"]*)"/)?.[1];
  return url && '\0' + url;
}

async function serve(files, config = {}) {
  const root = await fixture(files);
  const { extract, ...viteConfig } =
    typeof config === 'function' ? config(root) : config;
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'silent',
    server: { middlewareMode: true, ws: false },
    optimizeDeps: { noDiscovery: true },
    // Without @vitejs/plugin-react, Vite 6 and 7 compile JSX for React's classic runtime.
    esbuild: { jsx: 'automatic', jsxDev: true },
    plugins: [compiled({ extract })],
    ...viteConfig,
  });
  servers.push({ server, root });
  const client = server.environments.client;
  return {
    root,
    server,
    transform: async file => (await client.transformRequest(`/${file}`)).code,
    stylesheet: async code => {
      assert.ok(stylesheetImport(code));
      return (await client.transformRequest('\0virtual:vite-plugin-compiled-react.css?direct')).code;
    },
    // The script that carries the stylesheet to the browser, in the version a module imports.
    script: async code => (await client.transformRequest(stylesheetImport(code))).code,
  };
}
