async function edit({ root, server }, file, content) {
  await writeFile(join(root, file), content);
  server.watcher.emit('change', join(root, file));
}

async function eventually(read, pattern) {
  let value;
  for (let i = 0; i < 50 && !pattern.test(value); i++) {
    await new Promise(resolve => setTimeout(resolve, 20));
    value = await read();
  }
  assert.match(value, pattern);
  return value;
}

async function fixture(files) {
  const root = await mkdtemp(join(packageDir, '.fixture-'));
  roots.push(root);
  for (const [file, content] of Object.entries(files)) {
    await mkdir(dirname(join(root, file)), { recursive: true });
    await writeFile(join(root, file), content);
  }
  return root;
}

// The CSS a script inserts into a page.
function insertedStyles(code) {
  const { document } = new Window();
  runInNewContext(code, { document, external: {} });
  return [...document.querySelectorAll('style')].map(style => style.textContent).join('');
}

// A page that runs modules served to the browser, with Vite's client stubbed.
let pages = 0;
function browserPage(head = '') {
  const page = ++pages;
  const { document } = new Window({
    url: 'http://localhost/',
    settings: { disableCSSFileLoading: true },
  });
  document.head.innerHTML = head;
  const hotData = {};
  const viteClient = `data:text/javascript,
    export const createHotContext = () => ({ data: hotData, accept() {} });
    export const updateStyle = (id, css) => {
      const style = [...document.querySelectorAll('style')].find(style => style.dataset.viteDevId === id) ??
        document.head.appendChild(document.createElement('style'));
      style.dataset.viteDevId = id;
      style.textContent = css;
    };`;
  return {
    document,
    async run(code) {
      Object.assign(globalThis, { document, hotData });
      // Each page runs the module anew: import() caches by URL.
      code = `${code.replace(/(["'])\/@vite\/client\1/g, JSON.stringify(viteClient))}\n// page ${page}`;
      await import(`data:text/javascript,${encodeURIComponent(code)}`);
    },
  };
}

// The id of the stylesheet a module imports, with its query.
function stylesheetImport(code) {
  const url = code.match(/import "[^"]*\/@id\/__x00__(virtual:vite-plugin-compiled-react\.js[^"]*)"/)?.[1];
  return url && '\0' + url;
}

// Builds an app, or a library, with Compiled and React left external, in memory.
async function bundle(root, { build: buildOptions = {}, ...config } = {}) {
  const result = await build({
    root,
    configFile: false,
    logLevel: 'silent',
    plugins: [compiled()],
    ...config,
    build: {
      write: false,
      ...buildOptions,
      rollupOptions: { external: [/^react/, /^@compiled\/react/], ...buildOptions.rollupOptions },
    },
  });
  // A library's output comes per format.
  return (Array.isArray(result) ? result[0] : result).output;
}

// Each stylesheet of a library, and the CSS each `iife` or `umd` chunk inserts.
async function buildLibrary(files, lib, { build: buildOptions = {}, ...config } = {}) {
  const output = await bundle(await fixture(files), {
    ...config,
    build: {
      ...buildOptions,
      lib: { entry: 'src/index.jsx', formats: ['es'], ...lib },
      rollupOptions: {
        // The global variable an `iife` or `umd` library reads each of them from.
        output: { globals: () => 'external', ...buildOptions.rollupOptions?.output },
      },
    },
  });
  return Object.fromEntries(
    output.flatMap(({ fileName, source, code }) => {
      const css = fileName.endsWith('.css')
        ? source
        : /\.(iife|umd)\.c?js$/.test(fileName) && insertedStyles(code);
      return css ? [[fileName, css.replace(/\/\*\$vite\$:\d+\*\/|\n/g, '')]] : [];
    }),
  );
}

async function serve(files, config = {}) {
  const root = await fixture(files);
  const { extract, ...viteConfig } =
    typeof config === 'function' ? config(root) : config;
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'silent',
    server: { middlewareMode: true, ws: false },
    optimizeDeps: { noDiscovery: true },
    // Without @vitejs/plugin-react, Vite 6 and 7 compile JSX for React's classic runtime.
    esbuild: { jsx: 'automatic', jsxDev: true },
    plugins: [compiled({ extract })],
    ...viteConfig,
  });
  servers.push(server);
  const client = server.environments.client;
  // The stylesheet as Vite serves it.
  const sheet = async () =>
    (await client.transformRequest('\0virtual:vite-plugin-compiled-react.css?direct')).code;
  return {
    root,
    server,
    transform: async file => (await client.transformRequest(`/${file}`)).code,
    sheet,
    stylesheet: async code => {
      assert.ok(stylesheetImport(code));
      return sheet();
    },
    // The script that carries the stylesheet to the browser, in the version a module imports.
    script: async code => (await client.transformRequest(stylesheetImport(code))).code,
  };
}
