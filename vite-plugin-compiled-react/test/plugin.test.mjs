// Fixtures live in the package, so they resolve @compiled/react and react from its node_modules.
const packageDir = fileURLToPath(new URL('..', import.meta.url));
const servers = [];
after(async () => {
  for (const { server, root } of servers) {
    await server.close();
    await rm(root, { recursive: true });
  }
});

describe('the css prop', () => {
  it('compiles in .tsx modules without importing Compiled, into an extracted stylesheet', async () => {
    const { transform, stylesheet } = await serve({
      'src/Card.tsx': `import type { ReactNode } from 'react';
interface Props { children: ReactNode }
export const Card = ({ children }: Props) => (
  <section css={{ color: 'red' }}>{children}</section>
);`,
    });
    const code = await transform('src/Card.tsx');
    assert.match(code, /className: ax\(\["_syaz5scu"\]\)/);
    assert.doesNotMatch(code, /\bcss:/);
    assert.equal(await stylesheet(code), '._syaz5scu{color:red}');
    // React's dev runtime gets the line of <section>.
    assert.match(code, /lineNumber: 4,/);
  });

  it('reads values from imported modules, through string aliases and from the root', async () => {
    const { transform, stylesheet } = await serve(
      {
        'src/colors/a.ts': `export const red = 'red';`,
        'src/colors/b.ts': `export const blue = 'blue';`,
        'src/Page.jsx': `
          import { red } from '@colors/a';
          import { blue } from '#/colors/b';
          export const Page = () => <p css={{ color: red, ':hover': { color: blue } }} />;
        `,
      },
      root => ({
        resolve: { alias: { '@colors': `${root}/src/colors`, '#': '/src' } },
      }),
    );
    const css = await stylesheet(await transform('src/Page.jsx'));
    assert.match(css, /\{color:red\}/);
    assert.match(css, /:hover\{color:blue\}/);
  });

  it('uses the runtime instead when extraction is off for the command', async () => {
    const { transform } = await serve(
      { 'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;` },
      { extract: { build: true, serve: false } },
    );
    const code = await transform('src/Card.jsx');
    assert.match(code, /\bCS\b/);
    assert.doesNotMatch(code, /virtual:vite-plugin-compiled-react/);
  });
});

describe('which modules are compiled', () => {
  it("parses TypeScript in .ts modules, where `<string>value` isn't JSX", async () => {
    const { transform } = await serve({
      'src/styles.ts': `
        import { css } from '@compiled/react';
        const value: unknown = 'red';
        export const color = <string>value;
        export const styles = css({ color: 'blue' });
      `,
    });
    // Compiled replaces css() calls with null: their styles are compiled where they're used.
    assert.match(await transform('src/styles.ts'), /export const styles = null;/);
  });

  it('compiles styled components in .ts modules', async () => {
    const { transform, stylesheet } = await serve({
      'src/Box.ts': `
        import { styled } from '@compiled/react';
        export const Box = styled.div({ color: 'red' });
      `,
    });
    const code = await transform('src/Box.ts');
    assert.match(code, /className: ax\(\["_syaz5scu", __cmplp\.className\]\)/);
    assert.equal(await stylesheet(code), '._syaz5scu{color:red}');
  });

  it("leaves alone modules that can't use Compiled, and dependencies", async () => {
    const { transform } = await serve({
      'src/plain.ts': `import './plain.css'; export const n: number = 1;`,
      'src/plain.css': ``,
      'node_modules/dep/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;`,
    });
    assert.doesNotMatch(await transform('src/plain.ts'), /generated by @compiled/);
    assert.match(await transform('node_modules/dep/Card.jsx'), /\bcss:/);
  });
});

describe('the stylesheet', () => {
  it("holds every module's rules once, in Compiled's order, and is fetched anew by a module adding rules", async () => {
    const { transform, stylesheet } = await serve({
      'src/Wide.jsx': `export const Wide = () => <p css={{ '@media (min-width: 600px)': { color: 'blue' } }} />;`,
      'src/Card.jsx': `export const Card = () => <p css={{ color: 'red', '@media (min-width: 600px)': { color: 'blue' } }} />;`,
    });
    const wide = await transform('src/Wide.jsx');
    assert.equal(await stylesheet(wide), '@media (min-width:600px){._10s713q2{color:blue}}');
    const card = await transform('src/Card.jsx');
    assert.notEqual(stylesheetImport(card), stylesheetImport(wide));
    assert.equal(
      await stylesheet(card),
      '._syaz5scu{color:red}@media (min-width:600px){._10s713q2{color:blue}}',
    );
  });

  it('is linked by the HTML in a build, with the rules of lazily loaded modules', async () => {
    const root = await fixture({
      'index.html': `<script type="module" src="/src/main.jsx"></script>`,
      'src/main.jsx': `
        export const Card = () => <p css={{ color: 'red', '@media (min-width: 600px)': { color: 'blue' } }} />;
        import('./About.jsx');
      `,
      'src/About.jsx': `export const About = () => <p css={{ color: 'red', ':hover': { color: 'green' } }} />;`,
    });
    const { output } = await build({
      root,
      configFile: false,
      logLevel: 'silent',
      plugins: [compiled()],
      build: { write: false, rollupOptions: { external: [/^react/, /^@compiled\/react/] } },
    });
    const html = output.find(({ fileName }) => fileName === 'index.html').source;
    const links = [...html.matchAll(/<link rel="stylesheet"[^>]* href="\/([^"]+)"/g)];
    assert.equal(links.length, 1);
    const sheet = output.find(({ fileName }) => fileName === links[0][1]).source;
    assert.equal(
      sheet,
      '._syaz5scu{color:red}._30l3bf54:hover{color:green}@media (min-width:600px){._10s713q2{color:blue}}',
    );
  });
});

describe('React Server environments', () => {
  it('extract, and import the Compiled runtime', async () => {
    const { server } = await serve(
      { 'src/Card.jsx': `export const Card = () => <p css={{ color: 'red' }} />;` },
      {
        extract: false,
        environments: {
          rsc: {
            consumer: 'server',
            // Bundles @compiled/react, and React, whose modules only see the condition then.
            resolve: { conditions: ['react-server'], noExternal: true },
            optimizeDeps: { include: ['react', 'react/jsx-dev-runtime'] },
            dev: { createEnvironment: createRunnableDevEnvironment },
          },
        },
      },
    );
    const { Card } = await server.environments.rsc.runner.import('/src/Card.jsx');
    assert.equal(Card().props.className, '_syaz5scu');
  });
});

describe('dev', () => {
  it('re-compiles a module when a module it read values from changes', async () => {
    const fixture = await serve({
      'src/palette.ts': `export const red = 'red';`,
      'src/colors.ts': `import { red } from './palette'; export const color = red;`,
      'src/Card.jsx': `
        import { color } from './colors';
        export const Card = () => <p css={{ color }} />;
      `,
    });
    assert.match(await fixture.stylesheet(await fixture.transform('src/Card.jsx')), /color:red/);
    await edit(fixture, 'src/palette.ts', `export const red = 'blue';`);
    await eventually(
      async () => fixture.stylesheet(await fixture.transform('src/Card.jsx')),
      /color:blue/,
    );
  });

  it('re-compiles a module whose styles read an object through a re-export', async () => {
    const fixture = await serve({
      'src/palette.ts': `export const styles = { card: { color: 'red' } };`,
      'src/styles.ts': `export { styles } from './palette';`,
      'src/Card.jsx': `
        import { styles } from './styles';
        export const Card = () => <p css={styles.card} />;
      `,
    });
    assert.match(await fixture.stylesheet(await fixture.transform('src/Card.jsx')), /color:red/);
    await edit(fixture, 'src/palette.ts', `export const styles = { card: { color: 'blue' } };`);
    await eventually(
      async () => fixture.stylesheet(await fixture.transform('src/Card.jsx')),
      /color:blue/,
    );
  });

  it('updates a .tsx module whose import TypeScript removed once Compiled inlined its value', async () => {
    const fixture = await serve({
      'src/colors.ts': `export const primary = 'red';`,
      'src/tokens.ts': `export { primary } from './colors';`,
      'src/App.tsx': `
        import { primary } from './tokens';
        export const App = () => <p css={{ color: primary }} />;
        import.meta.hot.accept();
      `,
    });
    assert.doesNotMatch(await fixture.transform('src/App.tsx'), /tokens/);
    const sent = [];
    fixture.server.environments.client.hot.send = payload => sent.push(payload);
    await edit(fixture, 'src/colors.ts', `export const primary = 'blue';`);
    await eventually(async () => JSON.stringify(sent), /"path":"\/src\/App\.tsx"/);
    assert.match(await fixture.stylesheet(await fixture.transform('src/App.tsx')), /color:blue/);
  });
});

async function edit({ root, server }, file, content) {
  await writeFile(join(root, file), content);
  server.watcher.emit('change', join(root, file));
}

async function eventually(read, pattern) {
  let value;
  for (let i = 0; i < 50 && !pattern.test(value); i++) {
    await new Promise(resolve => setTimeout(resolve, 20));
    value = await read();
  }
  assert.match(value, pattern);
}

async function fixture(files) {
  const root = await mkdtemp(join(packageDir, '.fixture-'));
  for (const [file, content] of Object.entries(files)) {
    await mkdir(dirname(join(root, file)), { recursive: true });
    await writeFile(join(root, file), content);
  }
  return root;
}

function stylesheetImport(code) {
  return code.match(/import "(\/@id\/__x00__virtual:vite-plugin-compiled-react\.css[^"]*)"/)?.[1];
}

async function serve(files, config = {}) {
  const root = await fixture(files);
  const { extract, ...viteConfig } =
    typeof config === 'function' ? config(root) : config;
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'silent',
    server: { middlewareMode: true, ws: false },
    optimizeDeps: { noDiscovery: true },
    plugins: [compiled({ extract })],
    ...viteConfig,
  });
  servers.push({ server, root });
  const client = server.environments.client;
  return {
    root,
    server,
    transform: async file => (await client.transformRequest(`/${file}`)).code,
    stylesheet: async code => {
      assert.ok(stylesheetImport(code));
      return (await client.transformRequest('\0virtual:vite-plugin-compiled-react.css?direct')).code;
    },
  };
}
